#!/bin/sh

if [ "$CI" = true ]; then
  exit 0
fi

# source the root env for environment
if [ -f ".env" ]; then
  source .env
fi

if [ -z "$ENVIRONMENT" ]; then
  echo "ENVIRONMENT env variable must be set in root \`.env\` file"
  exit 1
fi

# load global config
CONFIG=$(cat platform/environment/config.json)

# MARK: discover app configs

# every app that needs environment variables has an `environment-config.json` at its root
# includes untracked (but not ignored) files so new apps work before their first commit
CONFIG_FILENAME="environment-config.json"
ALLOWED_KEYS='["$schema", "hasSecrets", "hasConvex", "publicPrefix", "infisicalPath"]'

CONFIG_FILES=$(git ls-files --cached --others --exclude-standard -- "*$CONFIG_FILENAME" "$CONFIG_FILENAME")

# validate every config before writing anything
APPS=""
for CONFIG_FILE in $CONFIG_FILES; do
  # tracked files deleted from the working tree are still listed by --cached
  if [ ! -f "$CONFIG_FILE" ]; then
    continue
  fi

  if ! jq -e 'type == "object"' "$CONFIG_FILE" > /dev/null 2>&1; then
    echo "ERROR: $CONFIG_FILE is not a valid JSON object"
    exit 1
  fi

  UNKNOWN_KEYS=$(jq -r --argjson allowed "$ALLOWED_KEYS" 'keys - $allowed | join(", ")' "$CONFIG_FILE")
  if [ -n "$UNKNOWN_KEYS" ]; then
    echo "ERROR: $CONFIG_FILE has unknown keys: $UNKNOWN_KEYS"
    echo "       allowed keys are defined in platform/environment/environment-config.schema.json"
    exit 1
  fi

  APPS="$APPS $(dirname "$CONFIG_FILE")"
done

if [ -z "$APPS" ]; then
  echo "No $CONFIG_FILENAME files found"
  exit 1
fi

# MARK: copy secrets

# load infisical domain and project id
INFISICAL_DOMAIN=$(echo $CONFIG | jq -r '.infisicalDomain')
INFISICAL_PROJECT_ID=$(echo $CONFIG | jq -r '.infisicalProjectId')

# convert local env key to infisical env key
INFISICAL_ENVIRONMENT_MAP='{"development": "dev", "production": "prod"}'
INFISICAL_ENVIRONMENT=$(echo $INFISICAL_ENVIRONMENT_MAP | jq -r ".$ENVIRONMENT")

# iterate over apps and load secrets for each app
# apps are paths relative to the repo root (e.g. `platform/transcription/service`)
for APP in $APPS; do
  APP_CONFIG="$APP/$CONFIG_FILENAME"

  echo "# ! IMPORTANT: This .env file is auto-generated by platform/environment." > $APP/.env.local
  echo "# ! Do not edit this file directly." >> $APP/.env.local
  echo "ENVIRONMENT=$ENVIRONMENT" >> $APP/.env.local

  HAS_SECRETS=$(jq -r '.hasSecrets // false' "$APP_CONFIG")
  if [ "$HAS_SECRETS" = false ]; then
    continue
  fi

  # secrets in infisical may live under a different path
  SECRETS_PATH=$(jq -r --arg app "$APP" '.infisicalPath // $app' "$APP_CONFIG")

  echo "Loading secrets for: $APP (infisical path: /$SECRETS_PATH)"

  SECRETS=$(
    infisical secrets \
      --domain $INFISICAL_DOMAIN \
      --env $INFISICAL_ENVIRONMENT \
      --projectId $INFISICAL_PROJECT_ID \
      --path /$SECRETS_PATH \
      --output dotenv
  )

  echo "$SECRETS" >> $APP/.env.local
done

# MARK: copy convex variables

if [ "$ENVIRONMENT" = "production" ]; then
  echo "Skipping convex environment variables for production environment"
  exit 0
fi

if [ ! -f "platform/convex/app/.env.local" ]; then
  echo "convex .env.local missing"
  exit 1
fi

source platform/convex/app/.env.local
if [ -z "$CONVEX_URL" ] || [ -z "$CONVEX_SITE_URL" ]; then
  echo "CONVEX_URL or CONVEX_SITE_URL missing"
  exit 1
fi

for APP in $APPS; do
  APP_CONFIG="$APP/$CONFIG_FILENAME"

  HAS_CONVEX=$(jq -r '.hasConvex // false' "$APP_CONFIG")
  if [ "$HAS_CONVEX" = false ]; then
    continue
  fi

  echo "Loading convex env variables for: $APP"
  PUBLIC_PREFIX=$(jq -r '.publicPrefix // ""' "$APP_CONFIG")
  echo "" >> $APP/.env.local
  echo "# convex variables" >> $APP/.env.local
  echo "${PUBLIC_PREFIX}CONVEX_URL=$CONVEX_URL" >> $APP/.env.local
  echo "${PUBLIC_PREFIX}CONVEX_SITE_URL=$CONVEX_SITE_URL" >> $APP/.env.local
done
