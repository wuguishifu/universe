import fs from 'fs';
import path from 'path';

import { EnvironmentConfig, environmentConfig } from '../environment';

const environment = environmentConfig.environmentKey;
console.log('Running environment setup post script for environment:', environment);

const filename = require.main?.filename;
if (!filename) {
  throw new Error('Could not determine the main module filename.');
}

const rootDir = path.join(path.dirname(filename), '..', '..', '..', '..', '..');

type AppConfig = {
  appType: 'next' | 'expo' | 'other';
  dir: string;
  extraEnvVariables?: (config: EnvironmentConfig) => Record<string, string | undefined>;
};

const appRootMap: Partial<Record<keyof EnvironmentConfig, AppConfig>> = {
  portfolio: {
    appType: 'next',
    dir: path.join(rootDir, 'apps', 'portfolio'),
  },
};

console.log('Updating .env files...');

Object.entries(appRootMap).forEach(([appKey, appConfig]) => {
  if (!fs.existsSync(appConfig.dir)) {
    console.warn('App root directory does not exist:', appConfig.dir);
    console.warn('Skipping .env file update for app:', appKey);
    return;
  }

  const type = appConfig.appType;

  const envConfig = environmentConfig[appKey as keyof EnvironmentConfig];
  const allEnvVariables = {
    ...(typeof envConfig === 'object' && envConfig),
    ...appConfig.extraEnvVariables?.(environmentConfig),
  };

  const envFileContents = `# ! IMPORTANT: This .env file is auto-generated by libs/environment.
# ! Do not edit this file directly.

${Object.entries(allEnvVariables)
  .filter((item): item is [string, string] => !!item[1])
  .map(([key, value]) => `${key}=${replaceLineBreaks(value)}`)
  .join('\n')}
${
  type === 'expo'
    ? `EXPO_PUBLIC_ENVIRONMENT=${environment}`
    : type === 'next'
      ? `NEXT_PUBLIC_ENVIRONMENT=${environment}`
      : `ENVIRONMENT=${environment}`
}
`;

  fs.writeFileSync(path.join(appConfig.dir, '.env'), envFileContents, 'utf-8');
  console.log(`Updated .env file for ${appKey} at ${appConfig.dir}/.env`);
});

function replaceLineBreaks(value: string) {
  return value.replace(/\n/g, '\\n');
}
